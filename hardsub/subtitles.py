from __future__ import annotations

import re
from pathlib import Path


def srt_time(seconds: float) -> str:
    total_ms = max(0, int(round(seconds * 1000)))
    hours, rem = divmod(total_ms, 3_600_000)
    minutes, rem = divmod(rem, 60_000)
    secs, ms = divmod(rem, 1000)
    return f"{hours:02d}:{minutes:02d}:{secs:02d},{ms:03d}"


def ass_time(seconds: float) -> str:
    total_cs = max(0, int(round(seconds * 100)))
    hours, rem = divmod(total_cs, 360_000)
    minutes, rem = divmod(rem, 6000)
    secs, cs = divmod(rem, 100)
    return f"{hours:d}:{minutes:02d}:{secs:02d}.{cs:02d}"


def build_srt(cues: list[dict]) -> str:
    blocks = []
    ordered = sorted(cues, key=lambda cue: (cue.get("start", 0), cue.get("end", 0)))
    for index, cue in enumerate(ordered, 1):
        text = (cue.get("text") or "").strip()
        if not text:
            continue
        blocks.append(
            f"{index}\n{srt_time(cue['start'])} --> {srt_time(cue['end'])}\n{text}\n"
        )
    return "\n".join(blocks)


def _ass_escape(text: str) -> str:
    text = text.replace("\\", "\\\\")
    text = text.replace("{", "\\{").replace("}", "\\}")
    text = text.replace("\r\n", "\n").replace("\r", "\n")
    return text.replace("\n", "\\N")


def _clamp(value: float, low: float, high: float) -> float:
    return max(low, min(high, value))


def build_ass(cues: list[dict], meta: dict) -> str:
    width = int(meta.get("display_width") or meta.get("width") or 1920)
    height = int(meta.get("display_height") or meta.get("height") or 1080)
    roi = meta.get("roi") or {"x": 0.03, "y": 0.52, "w": 0.94, "h": 0.45}
    line_height = float(meta.get("line_height_px") or 0)
    font_name = meta.get("font_name") or "Heiti SC"

    if line_height <= 0:
        line_height = height * 0.062
    font_size = int(round(_clamp(line_height * 0.9, 16, 160)))

    center_y = roi["y"] + roi["h"] / 2
    if center_y >= 0.5:
        alignment = 2
        margin_v = int(round((1.0 - (roi["y"] + roi["h"])) * height + height * 0.014))
    else:
        alignment = 8
        margin_v = int(round(roi["y"] * height + height * 0.014))
    margin_v = int(_clamp(margin_v, 8, height * 0.45))
    margin_h = int(round(width * 0.05))
    title = re.sub(r"[\r\n]+", " ", str(meta.get("title") or "HardSub")).strip()

    header = f"""[Script Info]
; Generated by HardSub Studio
Title: {title}
ScriptType: v4.00+
WrapStyle: 0
ScaledBorderAndShadow: yes
YCbCr Matrix: TV.709
PlayResX: {width}
PlayResY: {height}

[V4+ Styles]
Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding
Style: Chinese,{font_name},{font_size},&H00FFFFFF,&H00FFFFFF,&H00000000,&H64000000,0,0,0,0,100,100,0,0,1,2.2,0.8,{alignment},{margin_h},{margin_h},{margin_v},1

[Events]
Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text
"""
    rows = []
    for cue in sorted(cues, key=lambda item: (item.get("start", 0), item.get("end", 0))):
        text = (cue.get("text") or "").strip()
        if not text:
            continue
        start = ass_time(cue["start"])
        end = ass_time(max(cue["end"], cue["start"] + 0.03))
        rows.append(
            f"Dialogue: 0,{start},{end},Chinese,,0,0,0,,{_ass_escape(text)}"
        )
    return header + "\n".join(rows) + ("\n" if rows else "")


def write_text_file(path: str | Path, content: str, *, bom: bool = True):
    data = content.encode("utf-8")
    if bom:
        data = b"\xef\xbb\xbf" + data
    Path(path).write_bytes(data)


def safe_stem(filename: str | None) -> str:
    if not filename:
        return "subtitle"
    stem = Path(filename).stem
    stem = re.sub(r"[\x00-\x1f<>:\"/\\|?*]+", "_", stem).strip(" ._")
    return stem[:120] or "subtitle"


def median(values: list[float]) -> float:
    if not values:
        return 0.0
    values = sorted(values)
    mid = len(values) // 2
    if len(values) % 2:
        return float(values[mid])
    return float((values[mid - 1] + values[mid]) / 2)


def trim_cue_text(text: str, max_chars: int = 200) -> str:
    text = text.strip()
    if len(text) <= max_chars:
        return text
    return text[:max_chars].rstrip()
